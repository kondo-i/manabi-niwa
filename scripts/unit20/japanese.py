def generate(unit,i):
    if unit.startswith(('exp-japanese-', 'class-japanese-')):
        grade,key=unit.split('-g',1)[1].split('-',1)
        grade=int(grade)
    else:
        key=unit.removeprefix('japanese-')
        grade=2 if key in ('honorific-context','auxiliary-context','evidence-compare','little-mysteries','story-feelings') else 3 if key=='argument-reading' else 1
    if key in ('kanji','kanji-reading-a','kanji-reading-b'):
        vocab=READINGS[grade].split()
        j=(i+(10 if key.endswith('-b') else 0))%len(vocab)
        a,b,c=vocab[j].split(':')
        if key=='kanji' and i%3==2:
            return word(f'「{c}」を表す「{b}」を漢字で書こう。',a,f'「{a}」は「{c}」という意味。')
        return word(f'「{a}」の読みをひらがなで書こう。',b,f'{a}（{b}）は「{c}」を表す。')
    if key=='homophones':return cards(HOMOPHONES)[i%10]
    if key=='idioms':return cards(IDIOMS)[i%14]
    if key=='antonyms':
        a,b,c,d=ANTONYMS.split()[i%10].split(':')
        return choice(f'「{a}」と反対の意味を表す語を選ぼう。',b,c,d,f'「{a}」の対義語は「{b}」。')
    if key=='word-meanings':return cards(MEANINGS)[i%10]
    if key=='word-classes':return cards(CLASSES)[i%10]
    if key=='sentence-parts':
        a,b,c=SENTENCES[i%len(SENTENCES)]
        label=['主語','述語','述語を詳しくする修飾語'][i%3]
        opts=[a,b,c]
        ans=opts.pop(i%3)
        return choice(f'「{a}{c}{b}。」の{label}は？',ans,*opts,'「だれ・何が」を示すのが主語、「どうする」が述語。動作を詳しくする語句は修飾語。')
    if key in ('conjunctions','connective-context'):
        base=cards(LINKS)[i%10]
        if key=='connective-context':
            base['prompt']='【文の関係を考える】'+base['prompt']
        return base
    if key=='honorific-context':return cards(HONORIFIC)[i%10]
    if key=='auxiliary-context':return cards(AUXILIARY)[i%10]
    if key=='reference-context':return reading(i,'reference')
    if key=='little-mysteries':
        a,b,act=PAIRS[i%len(PAIRS)]
        return choice(f'【手がかり】棚に{a}と{b}がある。係は先に挙げた物を選び、机に置いた。\n係が机に置いたのは？',
                      a,b,'棚そのもの','「先に挙げた物」は、二つのうち最初に書かれた物。')
    if key=='story-feelings':return reading(i,'story')
    if key=='evidence-compare':return reading(i,'evidence')
    if key=='argument-reading':return reading(i,'argument')
    if key=='reading-practice':return reading(i,['paragraph','evidence','argument'][grade-1])
    if key=='foundations' and grade==2:
        topic=TOPICS[i%len(TOPICS)]
        return choice(f'【本文】{topic}の利用時間を調べるため、月曜日と金曜日を選んで観察した。\n文章が述べている調査方法は？',
                      '特定の二つの曜日を選んで観察した','一週間の全曜日で観察した','観察せず全員に質問した','観察した曜日は月曜日と金曜日。調査の範囲を正確に読む。')
    if key=='foundations':
        return reading(i+4 if grade==2 else i,['fact','evidence','argument'][grade-1])
    raise KeyError(unit)

